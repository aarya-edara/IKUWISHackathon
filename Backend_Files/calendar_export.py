import uuid
from datetime import datetime
from typing import List

from Backend_Files.Database_Functions.UserDatabaseFunctions import get_commitments, get_schedule_blocks


def _format_ics_datetime(dt_str: str) -> str:
    """Converts ISO datetime string YYYY-MM-DDTHH:MM:SS to ICS format YYYYMMDDTHHMMSSZ."""
    try:
        # Handle trailing Z or timezone if present
        clean_str = dt_str.replace("Z", "")
        dt = datetime.fromisoformat(clean_str)
        # Format as UTC/standard iCalendar timestamp
        return dt.strftime("%Y%m%dT%H%M%SZ")
    except Exception:
        return datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")


def generate_ics_content() -> str:
    """Generates an RFC 5545 compliant iCalendar string containing commitments and AI study blocks.

    Compatible with Google Calendar, Apple Calendar, and Microsoft Outlook.
    """
    blocks = get_schedule_blocks()
    commitments = get_commitments()

    now_stamp = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")

    lines: List[str] = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Smart Student Scheduler//AI Study Planner//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-WR-CALNAME:Student Study Timetable",
        "X-WR-TIMEZONE:UTC",
    ]

    # Add Commitments (Lectures, Gym, Shifts)
    for c in commitments:
        uid = f"commitment-{c['id']}-{uuid.uuid4().hex[:8]}@smartstudent.ai"
        dt_start = _format_ics_datetime(c["start_time"])
        dt_end = _format_ics_datetime(c["end_time"])
        summary = c["title"]
        desc = "Fixed Academic or Personal Commitment\\nGenerated by Smart Student Scheduler"

        lines.extend([
            "BEGIN:VEVENT",
            f"UID:{uid}",
            f"DTSTAMP:{now_stamp}",
            f"DTSTART:{dt_start}",
            f"DTEND:{dt_end}",
            f"SUMMARY:{summary}",
            f"DESCRIPTION:{desc}",
            "STATUS:CONFIRMED",
            "CATEGORIES:Commitment,Academic",
            "END:VEVENT",
        ])

    # Add AI Scheduled Study Blocks
    for b in blocks:
        uid = f"study-block-{b['id']}-{uuid.uuid4().hex[:8]}@smartstudent.ai"
        dt_start = _format_ics_datetime(b["start_time"])
        dt_end = _format_ics_datetime(b["end_time"])
        mod = b.get("module_code", "STUDY")
        summary = f"[{mod}] {b['title']}"
        reason = b.get("reason", "Allocated by AI Scheduler").replace("\n", " ")
        desc = (
            f"Module: {mod}\\n"
            f"AI Decision Rationale: {reason}\\n"
            f"Status: {'Locked by User' if b.get('is_locked') else 'AI Scheduled'}\\n\\n"
            "Smart Student Scheduler: Code does the maths, AI does the judgment."
        )

        lines.extend([
            "BEGIN:VEVENT",
            f"UID:{uid}",
            f"DTSTAMP:{now_stamp}",
            f"DTSTART:{dt_start}",
            f"DTEND:{dt_end}",
            f"SUMMARY:{summary}",
            f"DESCRIPTION:{desc}",
            "STATUS:CONFIRMED",
            "CATEGORIES:Study,Coursework",
            # 15-minute popup alarm
            "BEGIN:VALARM",
            "TRIGGER:-PT15M",
            "ACTION:DISPLAY",
            f"DESCRIPTION:Upcoming study block: {summary}",
            "END:VALARM",
            "END:VEVENT",
        ])

    lines.append("END:VCALENDAR")
    return "\r\n".join(lines)
